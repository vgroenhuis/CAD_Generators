"""Build the favicons of the web pages from the icons on the overview page.

Each generator card in web_app/static/index.html has an inline SVG icon. This script
turns those into favicons that stay readable at browser-tab size (16-32 px): the
drawing is put on a dark rounded tile in the site's colours, with thicker lines and
less transparent fills. The overview page itself gets a simple cube.

Output, in web_app/static/icons/:
  <page>.svg          the favicon (all current browsers)
  <page>-32.png       fallback for browsers without SVG favicons
  <page>-180.png      apple-touch-icon (iOS home screen)
and web_app/static/favicon.ico (16/32/48 px, for the browser's default request).
The <link> tags in each page's <head> are (re)written between FAVICON markers.

Run after changing an icon on the overview page:
    python web_app/tools/build_favicons.py
Needs Pillow and Playwright with a Chromium browser (for rendering the PNGs).
"""

from __future__ import annotations

import io
import os
import re
import sys
from pathlib import Path

from PIL import Image

STATIC = Path(__file__).resolve().parents[1] / "static"
ICONS = STATIC / "icons"
TILE = "#1a1d21"  # page background
ACCENT = "#5a8cd2"

OVERVIEW_ICON = f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64">
<rect width="64" height="64" rx="12" fill="{TILE}"/>
<path d="M32 10 L52 21 V43 L32 54 L12 43 V21 Z" fill="{ACCENT}" fill-opacity=".25" stroke="{ACCENT}" stroke-width="3.5" stroke-linejoin="round"/>
<path d="M12 21 L32 32 L52 21 M32 32 V54" fill="none" stroke="{ACCENT}" stroke-width="3.5" stroke-linejoin="round"/>
<path d="M32 10 L52 21 L32 32 L12 21 Z" fill="{ACCENT}" fill-opacity=".55"/>
</svg>
'''


def _bolder(svg_inner: str) -> str:
    """Thicker lines and stronger fills, so the drawing survives at 16-32 px."""
    def stroke(m):
        return f'stroke-width="{float(m.group(1)) * 2.2:g}"'

    def opacity(m):
        return f'fill-opacity="{min(0.9, float(m.group(1)) * 2.4):.2f}"'

    svg_inner = re.sub(r'stroke-width="([\d.]+)"', stroke, svg_inner)
    svg_inner = re.sub(r'fill-opacity="([\d.]+)"', opacity, svg_inner)
    return svg_inner.replace('stroke-dasharray="3 3"', 'stroke-dasharray="5 4"')


def card_icons() -> dict[str, str]:
    """page name -> favicon SVG, from the generator cards on the overview page."""
    html = (STATIC / "index.html").read_text(encoding="utf-8")
    icons = {}
    for m in re.finditer(r'<a class="card" href="([a-z0-9-]+)\.html">\s*(<svg class="icon"[^>]*>.*?</svg>)', html, re.S):
        page, svg = m.group(1), m.group(2)
        view_box = re.search(r'viewBox="([^"]+)"', svg).group(1)
        inner = svg[svg.index(">") + 1: svg.rindex("</svg>")]
        icons[page] = (
            '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64">\n'
            f'<rect width="64" height="64" rx="12" fill="{TILE}"/>\n'
            f'<svg x="4" y="4" width="56" height="56" viewBox="{view_box}">{_bolder(inner)}</svg>\n'
            "</svg>\n"
        )
    return icons


def render_pngs(svgs: dict[str, str], sizes: list[int]) -> dict[tuple[str, int], bytes]:
    from playwright.sync_api import sync_playwright

    out = {}
    with sync_playwright() as pw:
        exe = os.environ.get("CHROMIUM_PATH")
        browser = pw.chromium.launch(executable_path=exe) if exe else pw.chromium.launch()
        page = browser.new_page()
        for name, svg in svgs.items():
            for size in sizes:
                page.set_viewport_size({"width": size, "height": size})
                body = svg.replace("<svg ", f'<svg width="{size}" height="{size}" ', 1)
                page.set_content(f'<html><body style="margin:0;background:transparent">{body}</body></html>')
                out[(name, size)] = page.screenshot(omit_background=True, clip={"x": 0, "y": 0, "width": size, "height": size})
        browser.close()
    return out


def link_tags(name: str) -> str:
    return (
        "<!-- FAVICON (generated by web_app/tools/build_favicons.py) -->\n"
        f'<link rel="icon" type="image/svg+xml" href="icons/{name}.svg">\n'
        f'<link rel="icon" type="image/png" sizes="32x32" href="icons/{name}-32.png">\n'
        f'<link rel="apple-touch-icon" href="icons/{name}-180.png">\n'
        "<!-- /FAVICON -->\n"
    )


def update_page(page: Path, name: str) -> None:
    html = page.read_text(encoding="utf-8")
    html = re.sub(r"<!-- FAVICON .*?<!-- /FAVICON -->\n", "", html, flags=re.S)
    html = html.replace("</title>\n", "</title>\n" + link_tags(name), 1)
    page.write_text(html, encoding="utf-8")


def main() -> None:
    svgs = {"index": OVERVIEW_ICON, **card_icons()}
    ICONS.mkdir(exist_ok=True)
    for name, svg in svgs.items():
        (ICONS / f"{name}.svg").write_text(svg, encoding="utf-8")
    pngs = render_pngs(svgs, [16, 32, 48, 180])
    for (name, size), data in pngs.items():
        if size in (32, 180):
            (ICONS / f"{name}-{size}.png").write_bytes(data)
    ico = [Image.open(io.BytesIO(pngs[("index", s)])) for s in (16, 32, 48)]
    ico[2].save(STATIC / "favicon.ico", sizes=[(16, 16), (32, 32), (48, 48)], append_images=ico[:2])
    for name in svgs:
        page = STATIC / f"{name}.html"
        if page.exists():
            update_page(page, name)
    print(f"Wrote favicons for {', '.join(svgs)}", file=sys.stderr)


if __name__ == "__main__":
    main()
